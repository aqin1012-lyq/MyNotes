// Bundles the web app's content into the mini program, which has no backend: curriculum / problem list go into
// the main package, lessons and solutions into two subpackages (each package is capped at 2 MB).
// Run after `node tools/gen-app-json.mjs`: node tools/gen-miniprogram-content.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const STATIC = 'src/main/resources/static';
const MP = 'miniprogram';
const LIMIT = 2 * 1024 * 1024;

function write(file, value) {
  const src = `// Generated by tools/gen-miniprogram-content.mjs from ${STATIC}: do not edit.\nmodule.exports = ${JSON.stringify(value)};\n`;
  const size = Buffer.byteLength(src);
  if (size > LIMIT * 0.9) throw new Error(`${file} is ${size} bytes, too close to the 2 MB package limit`);
  mkdirSync(file.replace(/\/[^/]+$/, ''), { recursive: true });
  writeFileSync(file, src);
  console.log(`wrote ${file} (${(size / 1024).toFixed(0)} KB)`);
}

const mdDir = dir => Object.fromEntries(readdirSync(`${STATIC}/${dir}`).filter(f => f.endsWith('.md')).sort()
  .map(f => [f.slice(0, -3), readFileSync(`${STATIC}/${dir}/${f}`, 'utf8')]));

write(`${MP}/content/curriculum.js`, JSON.parse(readFileSync(`${STATIC}/curriculum.json`, 'utf8')));
write(`${MP}/content/algo.js`, JSON.parse(readFileSync(`${STATIC}/algo.json`, 'utf8')));
write(`${MP}/pkg-lessons/lessons.js`, mdDir('lessons'));
write(`${MP}/pkg-algo/solutions.js`, mdDir('algo'));
